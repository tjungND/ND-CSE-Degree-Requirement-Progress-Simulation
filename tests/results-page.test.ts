/** What a leak looks like, said independently of the rules that remove one. */
const GRADE_TOKEN = /(?<![\w§.+\-–’'])(A-|B\+|B-|C\+|C-|B|C|D|F|S|U|W|V)(?![\w+\-’'])/g;
/** A and I are also an article and a pronoun: a grade only where one stands. */
const A_OR_I = /\((A|I)\)|\bgraded (A|I)\b|(?<![\w’'])(A|I) is (?:below|your own)|\bwith an? (A|I)\b/g;
/** The rules' own words, which name a floor or a minimum, not anyone's grade. */
const RULE_WORDS = [/\b(?:a|the|of|an)\s+B\b/g, /\bB (?:or (?:higher|better|above)|floor|average|minimum)\b/g, /\(B\)/g, /\bgrade of [A-D]\b/g, /\bAppendix A\b/g, /\bU\.S\./g, /\bbelow [BC]\b/g, /\bC- (?:and|or) D\b/g];
function leaks(text: string): string[] {
  const found: string[] = [];
  let rest = text;
  for (const w of RULE_WORDS) rest = rest.replace(w, ' ');
  for (const m of rest.matchAll(GRADE_TOKEN)) found.push(`grade “${m[1]}”`);
  for (const m of text.matchAll(A_OR_I)) found.push(`grade “${m[0]}”`);
  for (const m of text.matchAll(/\bIncompletes?\b|\bwithdrawn \(W\)|\baudited \(V\)|\bfailed — earns|\bgraded [A-Z]\b|\bA U\b|\bU grades?\b|pass\/fail|mark “/g)) found.push(`“${m[0]}”`);
  if (/GPA|grade-point|\baverage\b/i.test(text)) for (const m of text.matchAll(/(?<![\w§.–-])\d{1,3}\.\d{2,3}(?![\d.–-]|\s*(?:cr\b|credit))/g)) found.push(`GPA figure ${m[0]}`);
  return found;
}

/** Every piece of text the page shows of a report: each card's facts and
 * notes, its deadline and status words, each course's lines, the warnings. */
function pageTexts(r: AuditReport): string[] {
  const out: string[] = [...r.warnings];
  const part = (p: DetailPart): string[] =>
    typeof p === 'string' ? [p] : 'note' in p ? [p.note] : 'warn' in p ? [p.warn] : 'check' in p ? [p.check] : 'lead' in p ? [p.lead, ...p.items] : [];
  for (const q of r.requirements) {
    out.push(q.title, ...(q.statusLabel ? [q.statusLabel] : []), ...(q.deadline?.label ? [q.deadline.label] : []));
    for (const p of q.shortDetailParts ?? q.detailParts ?? (q.detail ? [q.detail] : [])) out.push(...part(p));
  }
  for (const l of r.courseLines) out.push(l.text, ...(l.qualifier ? [l.qualifier.text] : []));
  return out;
}

const T = (season: Term['season'], year: number): Term => ({ season, year });
/** A record built to bring every grade sentence the engine has: a B- and a C
 * under the specialization floor, an F, a W, a V, an Incomplete in progress,
 * Incompletes past their deadline in consecutive semesters, research graded U
 * three semesters running, semester GPAs under the probation and dismissal
 * lines, a GPA under 3.0 the program's own courses alone would clear, another
 * university's course read from a mark, one graded S, one Incomplete there, an
 * unrecognized grade, and a graduation semester holding an Incomplete. */
function everyGrade(program: 'phd' | 'mscse'): Student {
  const nd = (courseId: string, term: Term, grade: string, credits = 3) => ({ courseId, credits, term, grade, origin: 'nd' });
  const elsewhere = (courseId: string, grade: string, extra: object = {}) => ({ courseId, credits: 3, term: T('fall', 2023), grade, origin: 'transfer', institution: 'Purdue University', degreeLevel: 'masters', ...extra });
  return {
    schemaVersion: 1,
    program,
    entryTerm: T('fall', 2024),
    gpa: 2.8,
    gpaSource: { basis: 'transcript-graduate', transcriptGpa: 2.8, programGpa: 3.12 },
    termGpas: [
      { term: T('fall', 2024), termGpa: 2.4, cumulativeGpa: 2.4 },
      { term: T('spring', 2025), termGpa: 1.8, cumulativeGpa: 2.1 },
      { term: T('fall', 2025), termGpa: 2.6, cumulativeGpa: 2.3 },
    ],
    priorMs: 'completed',
    graduationTerm: T('fall', 2026),
    milestones: { candidacyAdmitted: '2026-05-01', defensePassed: '2026-10-01', thesisDefensePassed: '2026-10-01' },
    attestations: {},
    courses: [
      nd('CSE 60111', T('fall', 2024), 'B-'),
      nd('CSE 60321', T('fall', 2024), 'C'),
      nd('CSE 60641', T('spring', 2025), 'F'),
      nd('CSE 60770', T('spring', 2025), 'W'),
      nd('CSE 60876', T('fall', 2025), 'V'),
      nd('CSE 60625', T('fall', 2026), 'I'),
      nd('CSE 60647', T('spring', 2025), 'I'),
      nd('CSE 60535', T('fall', 2025), 'I'),
      nd('CSE 98900', T('fall', 2024), 'U', 6),
      nd('CSE 98900', T('spring', 2025), 'U', 6),
      nd('CSE 98900', T('fall', 2025), 'U', 6),
      elsewhere('CS 50300', 'B', { transcriptMark: '85' }),
      elsewhere('CS 50800', 'S'),
      elsewhere('CS 52500', 'I'),
      elsewhere('CS 59000', 'Q'),
    ],
  } as unknown as Student;
}

describe('the results page names no grade (DGS 2026-11-22)', () => {
  it('rewords each sentence that names a grade, a mark or a GPA', () => {
    const cases: [string, string][] = [
      ['specialization course (§4.4.2): not counted — B- is below the B floor', 'specialization course (§4.4.2): not counted — its grade is below the B floor'],
      ['CSE 60111 (B-) is below the B floor — retake it or take another course (§4.4.2)', 'CSE 60111’s grade is below the B floor — retake it or take another course (§4.4.2)'],
      ['CSE 60111 (B-), CSE 60321 (C) are below the B floor — retake them or take another course (§4.4.2)', 'CSE 60111, CSE 60321: grades below the B floor — retake them or take another course (§4.4.2)'],
      ['Cumulative GPA 3.50 meets the 3.0 minimum', 'Cumulative GPA meets the 3.0 minimum'],
      ['Cumulative GPA 2.996 is below the 3.0 minimum', 'Cumulative GPA is below the 3.0 minimum'],
      ['Cumulative GPA of 3.0 or better: 3.60', 'Cumulative GPA of 3.0 or better: yes'],
      ['Cumulative GPA of 3.0 or better: 2.80 — below it', 'Cumulative GPA of 3.0 or better: below it'],
      ['Admitted to doctoral candidacy 2026-05-01. You show a 2.80 GPA — §2.2 requires a 3.0 for admission to candidacy; confirm your admission with the DGS.', 'Admitted to doctoral candidacy 2026-05-01. Your cumulative GPA is below the minimum — §2.2 requires a 3.0 for admission to candidacy; confirm your admission with the DGS.'],
      ['Your transcript shows a semester GPA below 2.0 (Fall 2025: 1.80) — the Academic Code lists this as a ground for dismissal', 'Your transcript shows a semester GPA below 2.0 (Fall 2025) — the Academic Code lists this as a ground for dismissal'],
      ['not counted — withdrawn (W) — earns no credit; it still counts as a registration for that semester’s full-time status (Academic Code §3.3)', 'not counted — earns no credit; it still counts as a registration for that semester’s full-time status (Academic Code §3.3)'],
      ['failed — earns no credit (DGS decision 2026-08-31)', 'not counted — earns no credit (DGS decision 2026-08-31)'],
      ['B is your own reading of the transcript’s mark “85” — the DGS checks it against the B that §5.2 requires', 'the grade here is your own reading of the transcript’s mark — the DGS checks it against the B that §5.2 requires'],
      ['A U in research in two consecutive semesters (Fall 2024, Spring 2025) — a Graduate School probation trigger (Academic Code §5.7.3)', 'Research not passed in two consecutive semesters (Fall 2024, Spring 2025) — a Graduate School probation trigger (Academic Code §5.7.3)'],
      ['Spring 2025: every course withdrawn — not counted as residence', 'Spring 2025: no course that counts — not counted as residence'],
      ['Your cumulative GPA is 2.80, below the 3.0 the award needs (§2.2)', 'Your cumulative GPA is below the 3.0 the award needs (§2.2)'],
    ];
    for (const [page, file] of cases) assert.equal(withoutGrades(page), file);
  });

  it('leaves the rules’ own words, credits and section numbers alone', () => {
    for (const text of [
      '3 distinct groups and 3 courses with a grade of B or higher are required (§4.4.2).',
      'Continuation in a CSE graduate degree program … require maintenance of at least a 3.0 (B) cumulative GPA.',
      'counts toward regular courses (2.64 cr); counted as 2.64 ND credits converted from the quarter system at 0.66 (transcript shows 4; §5.2)',
      'A cumulative GPA of 3.0 or better (§2.2; Academic Code §6.2.9; DGS Handbook §3.22.3)',
      'Cumulative GPA of at least 3.0',
      'counts toward regular courses (3 cr)',
    ])
      assert.equal(withoutGrades(text), text);
  });

  it('the made-up record brings every grade sentence, and none survives', () => {
    for (const program of ['phd', 'mscse'] as const) {
      const texts = pageTexts(audit(everyGrade(program), buildRules(), '2026-11-22'));
      const all = texts.join('\n');
      // Proof the record reaches the sentences (the page shows them all).
      const expected =
        program === 'phd'
          ? ['is below the B floor', 'withdrawn (W)', 'audited (V)', 'failed — earns no credit', 'Incomplete (I)', 'graded I (Incomplete)', 'graded S (pass/fail)', 'mark “85”', 'A U in research', 'Cumulative GPA 2.80', 'semester GPA below', 'courses alone average 3.12', 'You show a 2.80 GPA', "grade 'Q'"]
          : ['withdrawn (W)', 'audited (V)', 'failed — earns no credit', 'Incomplete (I)', 'Cumulative GPA 2.80', 'You show a 2.80 GPA'];
      for (const e of expected) assert.ok(all.includes(e), `${program}: the record should bring “${e}”`);
      const leaked = texts.map((t) => ({ t, l: leaks(withoutGrades(t)) })).filter((x) => x.l.length > 0);
      assert.deepEqual(leaked, [], `${program}: grades left in the file`);
    }
  });

  it('every scenario’s page text, with its grades left out, names none', () => {
    const leaked: string[] = [];
    for (const sc of allScenarios()) {
      const r = audit(sc.student, buildRules(sc.rules?.patch), sc.today);
      for (const t of pageTexts(r)) {
        const l = leaks(withoutGrades(t));
        if (l.length > 0) leaked.push(`${sc.name}: ${l.join(', ')} — ${withoutGrades(t).slice(0, 160)}`);
      }
    }
    assert.deepEqual(leaked, []);
  });
});
